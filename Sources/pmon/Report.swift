import ArgumentParser
import Foundation
import PmonCore

struct Report: ParsableCommand {
    static let configuration = CommandConfiguration(abstract: "Write a self-contained HTML report: timeline, slowdowns, offenders and findings.")

    @Option(help: "How far back to look, e.g. 24h or 7d.") var since = "7d"
    @Option(name: [.short, .long], help: "File to write.") var output = "pmon-report.html"
    @Flag(help: "HTML is the only format; accepted for clarity.") var html = false
    @Flag(help: "Open the report in the default browser.") var open = false
    @Flag(help: "Count slowdowns during which nobody was at the Mac as well.") var all = false
    @Option(help: "Database file.") var db: String = PmonPaths.database

    func run() throws {
        let database = try Database(path: db, readOnly: true)
        let now = Int64(Date().timeIntervalSince1970 * 1000), from = now - (try Fmt.span(since))
        let page = try ReportPage(db: database, since: from, now: now, label: since, includeAway: all).render()
        try page.write(toFile: output, atomically: true, encoding: .utf8)
        print("Wrote \(output) (\(page.utf8.count / 1024) kB).")
        if open { shell("/usr/bin/open", [output]) }
    }
}

/// Builds the report. Everything is inline (styles, SVG, one small script): the file can be
/// opened anywhere and nothing listens on a port.
struct ReportPage {
    let db: Database
    let since: Int64, now: Int64
    let label: String
    var includeAway = false

    func esc(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;")
    }

    func render() throws -> String {
        var host = "This Mac"
        try db.query("SELECT model, chip, p_cores, e_cores, mem_bytes FROM host WHERE host_id = 1") { r in
            host = "\(r.text(0)), \(r.text(1)) (\(r.int(2))P+\(r.int(3))E), \(r.int(4) >> 30) GB"
        }
        let totals = try Queries.totals(db, since: since, now: now, includeAway: includeAway)
        let episodes = try Queries.episodes(db, since: since, now: now)
        let offenders = try Queries.offenders(db, since: since, includeAway: includeAway, limit: 8)
        let findings = try Queries.findings(db, includeClosed: true, since: since)
        let background = try Queries.background(db, since: since, now: now)
        let timeline = try Queries.timeline(db, since: since, now: now)
        let openFindings = findings.filter { $0.status == "open" }.count

        var body = ""
        body += """
            <header>
              <h1>What slowed this Mac down</h1>
              <p class="sub">\(esc(host)) · \(Fmt.day(since)) \(Fmt.clock(since)) to \(Fmt.day(now)) \(Fmt.clock(now)) · generated by pmon \(PmonVersion.string)</p>
            </header>
            <section class="tiles">
              \(tile(String(totals.episodes), "slowdown\(totals.episodes == 1 ? "" : "s")" + (includeAway ? "" : " while you were at the Mac"),
                     includeAway ? (totals.away > 0 ? "\(totals.away) of them while nobody was present" : nil) : (totals.away > 0 ? "\(totals.away) more while away" : nil)))
              \(tile(Fmt.duration(totals.sluggishMs), "spent slowed down", totals.presentMs > 0 ? "\(Fmt.num(Double(totals.sluggishMs) * 100 / Double(totals.presentMs), 1)) % of the time you were present" : nil))
              \(tile(Fmt.duration(totals.observedMs), "observed awake", "\(Fmt.duration(totals.presentMs)) with you present"))
              \(tile(String(openFindings), "active finding\(openFindings == 1 ? "" : "s")", nil))
            </section>
            """
        body += section("Sluggishness over time",
                        "Highest index in each \(timeline.bucketMs == 60_000 ? "minute" : (timeline.bucketMs == 3_600_000 ? "hour" : "day")). 0 is idle, 100 is a saturated resource; a slowdown is recorded when the index stays at 60 or above.",
                        timelineChart(timeline.points, bucketMs: timeline.bucketMs) + timelineTable(timeline.points, bucketMs: timeline.bucketMs))
        body += section("Applications that caused slowdowns",
                        "Slowdown caused, in minutes: each application's share of the blame multiplied by the length of the slowdown, summed.",
                        offenderChart(offenders))
        body += section("Slowdowns", "Each recorded episode, with its bottleneck and main cause.", try episodeTable(episodes))
        body += section("Findings", "Chronic problems that do not show up as a single slowdown.", findingList(findings))
        body += section("Background cost", "What applications used while in focus less than 5 % of the time.", backgroundTable(background))

        return """
            <!doctype html>
            <html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
            <title>pmon report</title>
            <style>\(Self.css)</style></head>
            <body><main>\(body)</main><div id="tip" role="status"></div><script>\(Self.script)</script></body></html>
            """
    }

    func tile(_ value: String, _ label: String, _ note: String?) -> String {
        "<div class=\"tile\"><div class=\"value\">\(esc(value))</div><div class=\"label\">\(esc(label))</div>\(note.map { "<div class=\"note\">\(esc($0))</div>" } ?? "")</div>"
    }

    func section(_ title: String, _ sub: String, _ content: String) -> String {
        "<section><h2>\(esc(title))</h2><p class=\"sub\">\(esc(sub))</p>\(content)</section>"
    }

    func bucketLabel(_ ts: Int64, _ bucketMs: Int64) -> String {
        bucketMs >= 86_400_000 ? Fmt.day(ts) : "\(Fmt.day(ts)) \(Fmt.clock(ts))"
    }

    /// Column chart: one thin bar per bucket, a single hue, and a labelled reference line at the episode threshold.
    func timelineChart(_ points: [Queries.TimelinePoint], bucketMs: Int64) -> String {
        guard let first = points.first?.ts else { return "<p class=\"empty\">No data in this period yet.</p>" }
        let slots = max(Int((now - first) / bucketMs) + 1, 1)
        let w = 960.0, h = 240.0, left = 36.0, right = 12.0, top = 14.0, bottom = 28.0
        let plotW = w - left - right, plotH = h - top - bottom
        let slotW = plotW / Double(slots)
        let barW = max(min(slotW - 2, 14), 1)
        func y(_ v: Double) -> Double { top + plotH * (1 - v / 100) }
        var svg = "<svg viewBox=\"0 0 \(Int(w)) \(Int(h))\" role=\"img\" aria-label=\"Sluggishness index over time\" class=\"chart\">"
        for v in [0.0, 50, 100] {
            svg += "<line class=\"\(v == 0 ? "axis" : "grid")\" x1=\"\(left)\" x2=\"\(w - right)\" y1=\"\(y(v))\" y2=\"\(y(v))\"/>"
            svg += "<text class=\"tick\" x=\"\(left - 6)\" y=\"\(y(v) + 4)\" text-anchor=\"end\">\(Int(v))</text>"
        }
        svg += "<line class=\"ref\" x1=\"\(left)\" x2=\"\(w - right)\" y1=\"\(y(60))\" y2=\"\(y(60))\"/>"
        svg += "<text class=\"tick\" x=\"\(w - right)\" y=\"\(y(60) - 5)\" text-anchor=\"end\">slowdown threshold (60)</text>"
        // A handful of time labels along the axis.
        let labelEvery = max(slots / 6, 1)
        for i in stride(from: 0, to: slots, by: labelEvery) {
            let ts = first + Int64(i) * bucketMs
            let text = bucketMs >= 86_400_000 ? Fmt.day(ts) : (bucketMs >= 3_600_000 && slots > 30 ? Fmt.day(ts) : Fmt.clock(ts))
            svg += "<text class=\"tick\" x=\"\(left + (Double(i) + 0.5) * slotW)\" y=\"\(h - 8)\" text-anchor=\"middle\">\(esc(text))</text>"
        }
        for p in points {
            guard let max = p.max else { continue }
            let i = Double((p.ts - first) / bucketMs)
            let x = left + i * slotW + (slotW - barW) / 2
            let barTop = y(Double(max)), height = y(0) - barTop
            let r = min(4, barW / 2, height)
            if height > 0.5 {
                svg += "<path class=\"bar\" d=\"M\(x),\(y(0)) V\(barTop + r) Q\(x),\(barTop) \(x + r),\(barTop) H\(x + barW - r) Q\(x + barW),\(barTop) \(x + barW),\(barTop + r) V\(y(0)) Z\"/>"
            }
            let tip = "\(bucketLabel(p.ts, bucketMs))|highest \(max), average \(Fmt.num(p.avg ?? 0))|\(p.sluggishMs > 0 ? Fmt.duration(p.sluggishMs) + " in a slowdown" : "no slowdown")"
            // The hover target is the whole column, far larger than the bar itself.
            svg += "<rect class=\"hit\" x=\"\(left + i * slotW)\" y=\"\(top)\" width=\"\(slotW)\" height=\"\(plotH)\" data-tip=\"\(esc(tip))\"/>"
        }
        return svg + "</svg>"
    }

    /// The same data as a table, for readers who cannot use the chart.
    func timelineTable(_ points: [Queries.TimelinePoint], bucketMs: Int64) -> String {
        let notable = points.filter { ($0.max ?? 0) >= 40 }.suffix(60)
        guard !notable.isEmpty else { return "<details><summary>Table view</summary><p class=\"empty\">The index stayed below 40 throughout.</p></details>" }
        let rows = notable.map { "<tr><td>\(esc(bucketLabel($0.ts, bucketMs)))</td><td class=\"n\">\($0.max ?? 0)</td><td class=\"n\">\(Fmt.num($0.avg ?? 0))</td><td class=\"n\">\(Fmt.duration($0.sluggishMs))</td></tr>" }.joined()
        return "<details><summary>Table view (periods at 40 or above)</summary><table><thead><tr><th>Period</th><th class=\"n\">Highest</th><th class=\"n\">Average</th><th class=\"n\">In a slowdown</th></tr></thead><tbody>\(rows)</tbody></table></details>"
    }

    /// Horizontal bars, one per application, labelled with the value in text ink.
    func offenderChart(_ list: [Queries.Offender]) -> String {
        guard let maxMin = list.map(\.minutes).max(), maxMin > 0 else { return "<p class=\"empty\">No application caused a measurable slowdown in this period.</p>" }
        var html = "<div class=\"hbars\">"
        for o in list {
            let pct = max(o.minutes / maxMin * 100, 0.5)
            let tip = "\(o.app)|\(Fmt.num(o.minutes, 1)) min of slowdown caused|\(o.episodes) episode\(o.episodes == 1 ? "" : "s"), mostly \(Fmt.dimensionNames[o.via] ?? o.via)"
            html += "<div class=\"hrow\" data-tip=\"\(esc(tip))\"><div class=\"name\">\(esc(o.app))\(o.kind == "app" ? "" : " <span class=\"muted\">\(esc(o.kind))</span>")</div>"
            html += "<div class=\"track\"><div class=\"fill\" style=\"width:\(Fmt.num(pct, 1))%\"></div></div>"
            html += "<div class=\"val\">\(Fmt.num(o.minutes, 1)) min <span class=\"muted\">· \(esc(Fmt.dimensionNames[o.via] ?? o.via))</span></div></div>"
        }
        return html + "</div>"
    }

    func episodeTable(_ list: [Episode]) throws -> String {
        guard !list.isEmpty else { return "<p class=\"empty\">No slowdowns were recorded in this period.</p>" }
        var rows = ""
        for e in list.reversed().prefix(100) {
            let end = e.end ?? now
            let blame = try loadBlame(db, episode: e.id)
            let cause = blame.first { $0.role == "culprit" && $0.dim == e.dominant }
            let causeText = e.end == nil ? "in progress" : (cause.map { "\($0.app) (\(Fmt.num($0.share * 100)) %): \(describe($0))" } ?? "no single application")
            let victim = blame.first { $0.role == "victim" }.map { "; affected: \($0.app)" } ?? ""
            var context: [String] = []
            if let f = e.focusApp { context.append("\(f) in focus") }
            if !e.userPresent { context.append("nobody present") }
            if e.lowPower { context.append("Low Power Mode") }
            if e.afterWake { context.append("after wake") }
            rows += "<tr><td>\(esc(Fmt.day(e.start))) \(Fmt.clock(e.start))</td><td class=\"n\">\(Fmt.duration(end - e.start))</td><td class=\"n\">\(e.peak)</td>"
                + "<td>\(esc(Fmt.dimensionNames[e.dominant] ?? e.dominant))</td><td>\(esc(causeText + victim))</td><td class=\"muted\">\(esc(context.joined(separator: ", ")))</td></tr>"
        }
        return "<table><thead><tr><th>When</th><th class=\"n\">Length</th><th class=\"n\">Peak</th><th>Bottleneck</th><th>Main cause</th><th>Context</th></tr></thead><tbody>\(rows)</tbody></table>"
    }

    func findingList(_ list: [Queries.Finding]) -> String {
        guard !list.isEmpty else { return "<p class=\"empty\">Nothing found in this period.</p>" }
        let items = list.map { f -> String in
            let state = f.status == "open" ? (f.severity >= 2 ? "Needs attention" : "Active") : "Resolved"
            return "<li><span class=\"badge \(f.status == "open" ? (f.severity >= 2 ? "sev2" : "sev1") : "closed")\">\(state)</span> \(esc(Queries.sentence(f)))"
                + " <span class=\"muted\">since \(esc(Fmt.day(f.first))) \(Fmt.clock(f.first))</span></li>"
        }.joined()
        return "<ul class=\"findings\">\(items)</ul>"
    }

    func backgroundTable(_ list: [Queries.Background]) -> String {
        guard !list.isEmpty else { return "<p class=\"empty\">No background activity worth listing.</p>" }
        let rows = list.map { b in
            "<tr><td>\(esc(b.app))\(b.kind == "app" ? "" : " <span class=\"muted\">\(esc(b.kind))</span>")</td><td class=\"n\">\(Fmt.num(b.cpuCoreMinutes, 1))</td>"
                + "<td class=\"n\">\(Fmt.size(mb: b.peakMb))</td><td class=\"n\">\(b.energyMwh.map { Fmt.num($0, 1) } ?? "–")</td><td class=\"n\">\(Fmt.size(mb: b.writtenMb))</td></tr>"
        }.joined()
        return "<table><thead><tr><th>Application</th><th class=\"n\">CPU, core-minutes</th><th class=\"n\">Peak memory</th><th class=\"n\">Energy, mWh</th><th class=\"n\">Written</th></tr></thead><tbody>\(rows)</tbody></table>"
    }

