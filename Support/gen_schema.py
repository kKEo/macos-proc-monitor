#!/usr/bin/env python3
"""Generate Sources/PmonCore/Store/Schema.swift from the SQL blocks in DESIGN.md section 9.1-9.4.
The design document is the single source of truth for the schema. Run from the repository root."""
import re, sys
# Migration 1 is deployed, so its text is frozen. Later schema changes are hand-written
# migrations in Migrations.swift, and DESIGN.md section 9 describes the latest shape.
if "--force" not in sys.argv:
    sys.exit("Schema.v1 is frozen (it is deployed). Add a migration instead; --force only for a fresh project.")
doc = open("DESIGN.md").read()
part = doc[doc.index("### 9.1 Dimensions"):doc.index("### 9.5")]
blocks = re.findall(r"```sql\n(.*?)```", part, re.S)
rollup = [b for b in blocks if "_rollup_1h" in b]
other = [b for b in blocks if "_rollup_1h" not in b]
sql = "\n".join(other)
for grain in ("1m", "1h", "1d"):
    sql += "\n" + "\n".join(b.replace("_1h", "_" + grain) for b in rollup)
assert '"""#' not in sql
out = ('// GENERATED by Support/gen_schema.py from DESIGN.md section 9. Do not edit by hand.\n'
       '// Once released, schema changes go into a new migration instead of regenerating this file.\n\n'
       'enum Schema {\n    static let v1 = #"""\n' + sql.rstrip() + '\n"""#\n}\n')
open("Sources/PmonCore/Store/Schema.swift", "w").write(out)
print("tables:", len(re.findall(r"CREATE TABLE", sql)), "indexes:", len(re.findall(r"CREATE INDEX", sql)))
